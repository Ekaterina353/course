import pytest
from src.services import find_profitable_categories
import json


@pytest.fixture
def sample_transactions():
    """Фикстура для предоставления образца транзакций."""
    return [
        {"Дата операции": "2023-10-01", "Категория": "Супермаркеты", "Кешбэк": 100},
        {"Дата операции": "2023-10-05", "Категория": "Рестораны", "Кешбэк": 50},
        {"Дата операции": "2023-10-10", "Категория": "Супермаркеты", "Кешбэк": 150},
        {"Дата операции": "2023-11-01", "Категория": "Супермаркеты", "Кешбэк": 200},
        {"Дата операции": "2023-10-20", "Категория": "Развлечения", "Кешбэк": 75},
    ]


@pytest.mark.parametrize(
    "year, month, expected_categories, transactions",
    [
        (2023, 10, ["Супермаркеты"], [  # Тест 1: Только "Супермаркеты" лидируют в октябре
            {"Дата операции": "2023-10-01", "Категория": "Супермаркеты", "Кешбэк": 100},
            {"Дата операции": "2023-10-05", "Категория": "Рестораны", "Кешбэк": 50},
            {"Дата операции": "2023-10-10", "Категория": "Супермаркеты", "Кешбэк": 150},
        ]),
        (2023, 11, ["Супермаркеты"], [  # Тест 2: Только "Супермаркеты" в ноябре
            {"Дата операции": "2023-11-01", "Категория": "Супермаркеты", "Кешбэк": 200},
            {"Дата операции": "2023-11-05", "Категория": "Рестораны", "Кешбэк": 50},
        ]),
        (2023, 10, ["Супермаркеты", "Развлечения"], [ # Тест 3: "Супермаркеты" и "Развлечения" с одинаковым кешбеком
            {"Дата операции": "2023-10-01", "Категория": "Супермаркеты", "Кешбэк": 100},
            {"Дата операции": "2023-10-20", "Категория": "Развлечения", "Кешбэк": 100},
            {"Дата операции": "2023-10-05", "Категория": "Рестораны", "Кешбэк": 50},
        ]),
        (2023, 10, ["Супермаркеты"], [ # Тест 4: Больше транзакций, но лидируют "Супермаркеты"
            {"Дата операции": "2023-10-01", "Категория": "Супермаркеты", "Кешбэк": 100},
            {"Дата операции": "2023-10-05", "Категория": "Рестораны", "Кешбэк": 50},
            {"Дата операции": "2023-10-10", "Категория": "Супермаркеты", "Кешбэк": 150},
            {"Дата операции": "2023-10-15", "Категория": "Транспорт", "Кешбэк": 25},
            {"Дата операции": "2023-10-20", "Категория": "Развлечения", "Кешбэк": 75},
        ]),
        (2023, 10, [], []),  # Тест 5: Пустой список транзакций
        (2023, 10, ["Рестораны"], [ # Тест 6: Лидирует только одна категория
            {"Дата операции": "2023-10-05", "Категория": "Рестораны", "Кешбэк": 200},
            {"Дата операции": "2023-10-10", "Категория": "Супермаркеты", "Кешбэк": 150},
        ]),
    ]
)
def test_find_profitable_categories(year, month, expected_categories, transactions):
    """
    Параметризированный тест для функции find_profitable_categories.

    Args:
        year: Год для анализа.
        month: Месяц для анализа.
        expected_categories: Ожидаемый список самых прибыльных категорий.
        transactions: Список транзакций для теста.
    """
    result = find_profitable_categories(year, month, transactions)
    assert json.loads(result) == expected_categories
